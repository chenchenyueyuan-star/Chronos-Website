-- Chronos Snowflake schema. Run with a role allowed to create a database/schema/stage.
-- Use only for opted-in session measurements and media. No account passwords here.
CREATE DATABASE IF NOT EXISTS CHRONOS_ANALYTICS;
CREATE SCHEMA IF NOT EXISTS CHRONOS_ANALYTICS.WELLNESS;
USE DATABASE CHRONOS_ANALYTICS;
USE SCHEMA WELLNESS;

-- Actual JPG/PNG/MP4/MP3/WAV files live in the stage, not inside ordinary table cells.
CREATE STAGE IF NOT EXISTS CHRONOS_MEDIA_STAGE
    ENCRYPTION = (TYPE = 'SNOWFLAKE_FULL');

CREATE TABLE IF NOT EXISTS CHRONOS_MEDIA_ASSETS (
    ASSET_ID VARCHAR(36) NOT NULL,
    USER_ID VARCHAR(36) NOT NULL,
    SESSION_ID VARCHAR(36) NOT NULL,
    MEDIA_TYPE VARCHAR(32) NOT NULL, -- image_frame, video, audio, graph_image
    ORIGIN VARCHAR(32) NOT NULL,     -- camera, microphone, generated, chart_export
    STAGE_PATH VARCHAR(2048) NOT NULL,
    CONTENT_TYPE VARCHAR(100),
    FILE_SIZE_BYTES NUMBER(38,0),
    SESSION_OFFSET_SECONDS FLOAT,
    IS_RAW_CAPTURE BOOLEAN DEFAULT FALSE,
    CONSENT_RECORDED BOOLEAN DEFAULT FALSE,
    EXPIRES_AT TIMESTAMP_TZ,
    CREATED_AT TIMESTAMP_TZ DEFAULT CURRENT_TIMESTAMP(),
    PRIMARY KEY (ASSET_ID)
);

CREATE TABLE IF NOT EXISTS CHRONOS_BIOMETRIC_SAMPLES (
    SAMPLE_ID VARCHAR(36) NOT NULL,
    USER_ID VARCHAR(36) NOT NULL,
    SESSION_ID VARCHAR(36) NOT NULL,
    OBSERVED_AT TIMESTAMP_TZ NOT NULL,
    SESSION_OFFSET_SECONDS FLOAT,
    HEART_RATE_BPM FLOAT,
    BLINKS_PER_SECOND FLOAT,
    EMOTION_LABEL VARCHAR(100),
    EMOTION_CONFIDENCE FLOAT,
    -- Self-report and camera/model estimates are different measurements.
    SELF_REPORTED_ANXIETY_LEVEL FLOAT,
    ANXIETY_MODEL_ESTIMATE FLOAT,
    MEASUREMENT_SOURCE VARCHAR(100),
    MODEL_VERSION VARCHAR(100),
    RECORDED_AT TIMESTAMP_TZ DEFAULT CURRENT_TIMESTAMP(),
    PRIMARY KEY (SAMPLE_ID)
);

CREATE TABLE IF NOT EXISTS CHRONOS_SESSION_METRICS (
    METRIC_ID VARCHAR(36) NOT NULL,
    USER_ID VARCHAR(36) NOT NULL,
    SESSION_ID VARCHAR(36) NOT NULL,
    DURATION_SECONDS FLOAT,
    AVERAGE_HEART_RATE_BPM FLOAT,
    AVERAGE_BLINKS_PER_SECOND FLOAT,
    SAMPLE_COUNT NUMBER(38,0),
    SELF_REPORTED_ANXIETY_BEFORE FLOAT,
    SELF_REPORTED_ANXIETY_AFTER FLOAT,
    SUMMARY VARIANT,
    CREATED_AT TIMESTAMP_TZ DEFAULT CURRENT_TIMESTAMP(),
    PRIMARY KEY (METRIC_ID)
);

CREATE TABLE IF NOT EXISTS CHRONOS_SESSION_GRAPHS (
    GRAPH_ID VARCHAR(36) NOT NULL,
    USER_ID VARCHAR(36) NOT NULL,
    SESSION_ID VARCHAR(36) NOT NULL,
    GRAPH_TYPE VARCHAR(50) NOT NULL, -- heart_rate, blinking, emotion, etc.
    SERIES VARIANT NOT NULL,         -- JSON points: [{"seconds":0,"value":72}, ...]
    GRAPH_IMAGE_ASSET_ID VARCHAR(36),
    CREATED_AT TIMESTAMP_TZ DEFAULT CURRENT_TIMESTAMP(),
    PRIMARY KEY (GRAPH_ID)
);

-- IDs are the same UUID strings used by TigerData; Snowflake cannot enforce a
-- relational FK back to a separate PostgreSQL database. The app verifies ownership.
